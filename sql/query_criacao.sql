--Criação do database
create database escola_aprende_mais;

use escola_aprende_mais;

--Criação das tabelas
--Criação da tabela cursos(dimensão)
CREATE TABLE cursos (
    curso_id       INT           PRIMARY KEY,
    nome_curso     VARCHAR(60)   NOT NULL,
    categoria      VARCHAR(30)   NOT NULL,
    preco          DECIMAL(8,2)  NOT NULL,
    carga_horaria  INT           NOT NULL
);

--Criação da tabela alunos(dimensão)
CREATE TABLE alunos (
    aluno_id       INT           PRIMARY KEY,
    nome           VARCHAR(60)   NOT NULL,
    cidade         VARCHAR(40)   NOT NULL,
    estado         CHAR(2)       NOT NULL,
    data_cadastro  DATE          NOT NULL
);

--Criação da tabela matriculas(fato)
CREATE TABLE matriculas (
    matricula_id     INT           PRIMARY KEY,
    aluno_id         INT           NOT NULL REFERENCES alunos(aluno_id),
    curso_id         INT           NOT NULL REFERENCES cursos(curso_id),
    data_matricula   DATE          NOT NULL,
    valor_pago       DECIMAL(8,2)  NOT NULL,
    status           VARCHAR(20)   NOT NULL,
    nota_final       DECIMAL(3,1)  NULL,
    forma_pagamento  VARCHAR(20)   NULL
);

